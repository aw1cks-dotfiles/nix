#!/usr/bin/env python3
"""Apply Nix's complete private Serve config; marker records activation, not routes."""

import json
import os
from pathlib import Path
import re
import stat
import subprocess
import sys
import tempfile


class ApplyError(Exception):
    """An actionable failure; keep the activation marker available for retry."""


def load_json(stream):
    try:
        return json.load(stream)
    except (ValueError, UnicodeError) as error:
        raise ApplyError(f"Invalid JSON: {error}") from error


def hostname(value):
    if not isinstance(value, str) or "." not in value:
        raise ApplyError("hostname must be a full DNS name")
    return value.removesuffix(".").lower()


def settings(value):
    keys = {"tailscale", "hostname", "markerFile", "configFile", "enabled"}
    if not isinstance(value, dict) or set(value) != keys:
        raise ApplyError(f"Settings require exactly {', '.join(sorted(keys))}")
    if type(value["enabled"]) is not bool:
        raise ApplyError("enabled must be a boolean")
    for key in ("tailscale", "markerFile", "configFile"):
        if (
            not isinstance(value[key], str)
            or not os.path.isabs(value[key])
            or "\0" in value[key]
        ):
            raise ApplyError(f"{key} must be an absolute path")
    result = dict(value)
    result["hostname"] = (
        hostname(value["hostname"]) if value["enabled"] or value["hostname"] else ""
    )
    if Path(value["markerFile"]).resolve().is_relative_to("/nix/store"):
        raise ApplyError("markerFile must be outside the Nix store")
    return result


def validate_config(value, host):
    """Accept only the exact HTTPS root/IPv4-loopback shape generated by Nix."""
    if value == {}:
        return value
    if not isinstance(value, dict) or set(value) != {"TCP", "Web"}:
        raise ApplyError(
            "Desired Serve config must contain only TCP and Web (no Funnel)"
        )
    tcp, web = value["TCP"], value["Web"]
    if not isinstance(tcp, dict) or not tcp or not isinstance(web, dict):
        raise ApplyError("Desired Serve TCP and Web must be nonempty objects")
    expected = set()
    for port, listener in tcp.items():
        if not re.fullmatch(r"[1-9][0-9]{0,4}", port) or int(port) > 65535:
            raise ApplyError("Desired HTTPS port must be from 1 to 65535")
        if listener != {"HTTPS": True} or type(listener.get("HTTPS")) is not bool:
            raise ApplyError("Desired listeners must be HTTPS only")
        address = f"{host}:{port}"
        expected.add(address)
        endpoint = web.get(address)
        if not isinstance(endpoint, dict) or set(endpoint) != {"Handlers"}:
            raise ApplyError("Desired Web endpoint must contain only Handlers")
        handlers = endpoint["Handlers"]
        if not isinstance(handlers, dict) or set(handlers) != {"/"}:
            raise ApplyError("Desired Web endpoint must contain only the root handler")
        handler = handlers["/"]
        if not isinstance(handler, dict) or set(handler) != {"Proxy"}:
            raise ApplyError("Desired root handler must contain only Proxy")
        proxy = handler["Proxy"]
        match = (
            re.fullmatch(r"http://127\.0\.0\.1:([1-9][0-9]{0,4})", proxy)
            if isinstance(proxy, str)
            else None
        )
        if match is None or int(match[1]) > 65535:
            raise ApplyError(
                "Desired proxies must use http://127.0.0.1 with a valid port"
            )
    if set(web) != expected:
        raise ApplyError(
            "Desired Web endpoints must match this hostname and the HTTPS ports"
        )
    return value


class Marker:
    def __init__(self, path):
        self.path = Path(path)

    def parent(self, create=False):
        if create:
            self.path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
        try:
            info = self.path.parent.lstat()
        except FileNotFoundError:
            return False
        if not stat.S_ISDIR(info.st_mode) or info.st_uid != os.getuid():
            raise ApplyError(
                "Marker parent must be a real directory owned by the current user"
            )
        if create:
            self.path.parent.chmod(0o700)
        return True

    def load(self):
        if not self.parent():
            return None
        try:
            descriptor = os.open(self.path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
        except FileNotFoundError:
            return None
        with os.fdopen(descriptor, encoding="utf-8") as stream:
            info = os.fstat(stream.fileno())
            if not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid():
                raise ApplyError("Marker must be a real file owned by the current user")
            os.fchmod(stream.fileno(), 0o600)
            self.path.parent.chmod(0o700)
            value = load_json(stream)
        if (
            not isinstance(value, dict)
            or set(value) != {"version", "hostname"}
            or type(value["version"]) is not int
            or value["version"] != 1
        ):
            raise ApplyError(
                "Invalid activation marker: expected version 1 and hostname"
            )
        return hostname(value["hostname"])

    def save(self, host):
        self.parent(create=True)
        descriptor, temporary = tempfile.mkstemp(
            prefix=".managed-", dir=self.path.parent
        )
        try:
            with os.fdopen(descriptor, "w", encoding="utf-8") as stream:
                json.dump({"version": 1, "hostname": host}, stream)
                stream.flush()
                os.fsync(stream.fileno())
            os.replace(temporary, self.path)
        finally:
            if os.path.exists(temporary):
                os.unlink(temporary)

    def remove(self):
        self.path.unlink()


class Tailscale:
    def __init__(self, executable):
        self.executable = executable

    def run(self, arguments, payload=None):
        try:
            result = subprocess.run(
                [self.executable, *arguments],
                input=payload,
                capture_output=True,
                text=True,
                timeout=30,
                check=False,
            )
        except (OSError, subprocess.TimeoutExpired) as error:
            raise ApplyError(
                f"Cannot run Tailscale CLI: {error}; activation marker retained for retry"
            ) from error
        if result.returncode:
            dependency = (
                " Requires tailscale serve set-raw (verified with 1.104.4); no reset fallback."
                if payload is not None
                else ""
            )
            raise ApplyError(
                f"Tailscale {' '.join(arguments)} failed: {result.stderr.strip() or result.stdout.strip()}."
                f"{dependency} Activation marker retained for retry."
            )
        if payload is None:
            try:
                return json.loads(result.stdout)
            except (ValueError, UnicodeError) as error:
                raise ApplyError(f"Tailscale returned invalid JSON: {error}") from error
        return None

    def status(self):
        return self.run(["status", "--json"])

    def config(self):
        return self.run(["serve", "status", "--json"])

    def apply(self, config):
        # This undocumented native command replaces the entire ipn.ServeConfig.
        self.run(["serve", "set-raw"], json.dumps(config))


def check_backend(client, host):
    status = client.status()
    if not isinstance(status, dict) or status.get("BackendState") != "Running":
        raise ApplyError("Tailscale backend must be Running; refusing to change Serve")
    own = status.get("Self")
    if not isinstance(own, dict) or hostname(own.get("DNSName")) != host:
        raise ApplyError(
            f"Tailscale node identity must match {host}; refusing to change Serve"
        )


def transition_config(desired, current):
    """Release incompatible listeners using only a subset of Nix's desired state."""
    listeners = current.get("TCP") or {}
    foreground = (current.get("Foreground") or {}).values()
    blocked = {
        port
        for port in desired.get("TCP", {})
        if (port in listeners and listeners[port].get("HTTPS") is not True)
        or any(port in (entry.get("TCP") or {}) for entry in foreground)
    }
    if not blocked:
        return None
    tcp = {port: value for port, value in desired["TCP"].items() if port not in blocked}
    if not tcp:
        return {}
    return {
        "TCP": tcp,
        "Web": {
            address: value
            for address, value in desired["Web"].items()
            if address.rsplit(":", 1)[-1] not in blocked
        },
    }


def apply(configuration, client=None):
    options = settings(configuration)
    marker = Marker(options["markerFile"])
    saved = marker.load()
    if not options["enabled"] and saved is None:
        return
    host = options["hostname"] if options["enabled"] else saved
    if saved is not None and options["hostname"] and saved != options["hostname"]:
        raise ApplyError(
            "Activation marker hostname differs from settings; refusing to change Serve"
        )
    desired = {}
    if options["enabled"]:
        with open(options["configFile"], encoding="utf-8") as stream:
            desired = validate_config(load_json(stream), host)
    client = client if client is not None else Tailscale(options["tailscale"])
    check_backend(client, host)
    current = client.config()
    check_backend(client, host)
    if current is None:
        current = {}
    if not isinstance(current, dict):
        raise ApplyError("Current Serve config must be an object or null")
    if options["enabled"] and saved is None:
        # Record intent before the first write, including a lost CLI reply/crash.
        marker.save(host)
    if current != desired:
        staged = transition_config(desired, current)
        if staged is not None:
            check_backend(client, host)
            client.apply(staged)
        check_backend(client, host)
        client.apply(desired)
    if not options["enabled"]:
        check_backend(client, host)
        marker.remove()


def main(arguments):
    if len(arguments) != 1:
        print("Usage: apply.py SETTINGS.json", file=sys.stderr)
        return 2
    try:
        with open(arguments[0], encoding="utf-8") as stream:
            apply(load_json(stream))
    except (ApplyError, OSError) as error:
        print(f"tailscale-serve: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
